"""Threshold sweep and seeded-resampling evaluation for the PubMed pipeline.

This script does not train a model or modify a checkpoint. It reuses the genuine
abstract references and sentence scores recorded by Experiment 2, reconstructs
predictions from the local PubMed test split, and evaluates mean + k*std
thresholds with the original Top-3 fallback. Multiple seeds control paired
document bootstrap resampling only; they are not training seeds.

Run from the repository root, for example:

    python scripts/pubmed_threshold_multiseed_evaluation.py \
      --threshold-multipliers 0 0.25 0.5 0.75 1.0 \
      --seeds 13 21 42 87 101
"""

from __future__ import annotations

import argparse
import ast
import csv
import json
from pathlib import Path

import numpy as np
from datasets import load_from_disk
from rouge_score import rouge_scorer


DEFAULT_INPUT = Path(
    "results/experiment_02_threshold_ablation/per_document_threshold_ablation.csv"
)
DEFAULT_DATASET = Path("local_dataset/test")
DEFAULT_OUTPUT = Path("results/pubmed_threshold_multiseed_evaluation")
ROUGE_KEYS = ("rouge1", "rouge2", "rougeL")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--threshold-multipliers",
        type=float,
        nargs="+",
        default=[0.0, 0.25, 0.5, 0.75, 1.0],
        help="Values of k in mean(score) + k * population_std(score).",
    )
    parser.add_argument(
        "--seeds",
        type=int,
        nargs="+",
        default=[13, 21, 42, 87, 101],
        help="Seeds for paired document bootstrap resampling.",
    )
    parser.add_argument(
        "--resamples-per-seed",
        type=int,
        default=1,
        help="Number of N-document bootstrap samples generated by each seed.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Allow replacement of files in the output directory.",
    )
    return parser.parse_args()


def load_recorded_documents(path: Path) -> list[dict]:
    """Load one shared score/reference record per document from Experiment 2."""
    if not path.is_file():
        raise FileNotFoundError(f"Recorded Experiment 2 scores not found: {path}")

    records = []
    with path.open(newline="", encoding="utf-8") as handle:
        for row in csv.DictReader(handle):
            if row["strategy"] != "dynamic_mean_plus_0.5std":
                continue
            if row["evaluated"].lower() != "true":
                continue
            records.append(
                {
                    "document_index": int(row["document_index"]),
                    "valid_length": int(row["valid_length"]),
                    "scores": np.asarray(ast.literal_eval(row["sentence_scores"]), dtype=float),
                    "reference": row["reference"],
                }
            )

    records.sort(key=lambda item: item["document_index"])
    ids = [item["document_index"] for item in records]
    if not records or len(ids) != len(set(ids)):
        raise ValueError("Input must contain unique evaluated document records.")
    return records


def select_indices(scores: np.ndarray, multiplier: float) -> tuple[list[int], float, bool]:
    """Apply the original strict threshold and Top-3 fallback."""
    threshold = float(scores.mean() + multiplier * scores.std(ddof=0))
    selected = np.flatnonzero(scores > threshold).tolist()
    fallback = len(selected) < 2
    if fallback:
        top_k = min(3, len(scores))
        selected = np.argsort(scores)[-top_k:][::-1].tolist()
    return sorted(int(index) for index in selected), threshold, fallback


def refuse_overwrite(paths: list[Path], overwrite: bool) -> None:
    existing = [str(path) for path in paths if path.exists()]
    if existing and not overwrite:
        joined = "\n  ".join(existing)
        raise FileExistsError(f"Refusing to overwrite existing outputs:\n  {joined}")


def main() -> None:
    args = parse_args()
    if args.resamples_per_seed < 1:
        raise ValueError("--resamples-per-seed must be positive")
    if len(args.seeds) != len(set(args.seeds)):
        raise ValueError("--seeds must not contain duplicates")

    documents = load_recorded_documents(args.input)
    dataset = load_from_disk(str(args.dataset))
    scorer = rouge_scorer.RougeScorer(list(ROUGE_KEYS), use_stemmer=True)

    per_document_path = args.output_dir / "per_document_threshold_scores.csv"
    per_seed_path = args.output_dir / "per_seed_bootstrap_results.csv"
    aggregate_path = args.output_dir / "aggregate_results.json"
    refuse_overwrite([per_document_path, per_seed_path, aggregate_path], args.overwrite)
    args.output_dir.mkdir(parents=True, exist_ok=True)

    per_document = []
    score_arrays: dict[float, np.ndarray] = {}
    for multiplier in args.threshold_multipliers:
        metric_rows = []
        for record in documents:
            doc_index = record["document_index"]
            sentences = dataset[doc_index]["text"]
            valid_length = min(record["valid_length"], len(sentences), len(record["scores"]))
            if valid_length < 1:
                raise ValueError(f"Document {doc_index} has no valid positions")
            valid_scores = record["scores"][:valid_length]
            selected, threshold, fallback = select_indices(valid_scores, multiplier)
            prediction = " ".join(sentences[index] for index in selected)
            result = scorer.score(record["reference"], prediction)
            metrics = [result[key].fmeasure for key in ROUGE_KEYS]
            metric_rows.append(metrics)
            per_document.append(
                {
                    "document_index": doc_index,
                    "threshold_multiplier": multiplier,
                    "threshold": threshold,
                    "fallback_used": fallback,
                    "selected_indices": json.dumps(selected),
                    "selected_sentence_count": len(selected),
                    "prediction": prediction,
                    "reference": record["reference"],
                    "rouge1_f1": metrics[0],
                    "rouge2_f1": metrics[1],
                    "rougeL_f1": metrics[2],
                }
            )
        score_arrays[multiplier] = np.asarray(metric_rows, dtype=float)

    fieldnames = list(per_document[0])
    with per_document_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(per_document)

    sample_size = len(documents)
    seed_rows = []
    for seed in args.seeds:
        rng = np.random.default_rng(seed)
        for resample in range(args.resamples_per_seed):
            indices = rng.integers(0, sample_size, size=sample_size)
            for multiplier, values in score_arrays.items():
                means = values[indices].mean(axis=0)
                seed_rows.append(
                    {
                        "seed": seed,
                        "resample": resample,
                        "sample_size": sample_size,
                        "threshold_multiplier": multiplier,
                        "rouge1_f1": means[0],
                        "rouge2_f1": means[1],
                        "rougeL_f1": means[2],
                    }
                )

    with per_seed_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(seed_rows[0]))
        writer.writeheader()
        writer.writerows(seed_rows)

    aggregate = {
        "status": "generated by evaluation; no training performed",
        "input": str(args.input),
        "dataset": str(args.dataset),
        "documents": sample_size,
        "reference_protocol": "genuine PubMed summary abstracts recorded by Experiment 2",
        "rouge": {
            "library": "rouge-score",
            "metrics": list(ROUGE_KEYS),
            "statistic": "F1",
            "stemming": True,
            "aggregation": "macro mean over documents",
        },
        "selection": "score > mean(score) + k * population_std(score); original Top-3 fallback when fewer than two pass",
        "threshold_multipliers": args.threshold_multipliers,
        "multi_seed_scope": "paired N-document bootstrap resampling; not model training",
        "seeds": args.seeds,
        "resamples_per_seed": args.resamples_per_seed,
        "full_sample_means": {
            str(multiplier): dict(zip(ROUGE_KEYS, values.mean(axis=0).tolist()))
            for multiplier, values in score_arrays.items()
        },
    }
    aggregate_path.write_text(json.dumps(aggregate, indent=2) + "\n", encoding="utf-8")

    print(f"Saved {per_document_path}")
    print(f"Saved {per_seed_path}")
    print(f"Saved {aggregate_path}")


if __name__ == "__main__":
    main()
